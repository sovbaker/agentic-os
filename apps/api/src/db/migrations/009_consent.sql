-- Согласие пользователя.
--
-- Хранится на сервере, а не флажком в клиенте. Флажок в клиенте отвечает
-- на вопрос «показывать ли экран», а нужен ответ на вопрос «согласие
-- было?» — и его задаём не мы, а ревью App Store и юрист. Ответ «у
-- пользователя в телефоне что-то записано» не подтверждает ничего:
-- переустановка стирает его вместе с доказательством.
--
-- Версия, а не булев флаг: изменившаяся политика — это новое согласие,
-- и старая отметка не должна засчитываться за него.

ALTER TABLE app_user ADD COLUMN IF NOT EXISTS consent_version text;
ALTER TABLE app_user ADD COLUMN IF NOT EXISTS consent_at timestamptz;
